BODY_FONT = Font(name="微软雅黑", size=9)
TITLE_FONT = Font(name="微软雅黑", size=14, bold=True, color="1F3864")
NOTE_FONT = Font(name="微软雅黑", size=9, italic=True, color="595959")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
GREEN = PatternFill("solid", fgColor="E2EFDA")
YELLOW = PatternFill("solid", fgColor="FFF2CC")
GREY = PatternFill("solid", fgColor="F2F2F2")
RED = PatternFill("solid", fgColor="FCE4E4")
BLUE = PatternFill("solid", fgColor="DDEBF7")

MARK_FILL = {"●": GREEN, "◐": YELLOW, "○": GREY}


def style_sheet(ws, title, subtitle, headers, rows, widths, freeze="B4", wrap_cols=()):
    ws.sheet_view.showGridLines = False
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    ws.row_dimensions[1].height = 26

    ws["A2"] = subtitle
    ws["A2"].font = NOTE_FONT
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(headers))
    ws.row_dimensions[2].height = 18

    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=3, column=c, value=h)
        cell.fill = HDR_FILL
        cell.font = HDR_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[3].height = 34

    for r, row in enumerate(rows, 4):
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.font = BODY_FONT
            cell.border = BORDER
            if c in wrap_cols:
                cell.alignment = Alignment(vertical="top", wrap_text=True)
            elif c == 1:
                cell.alignment = Alignment(vertical="center", wrap_text=True)
                cell.font = Font(name="微软雅黑", size=9, bold=True)
            else:
                cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            sval = str(val) if isinstance(val, str) else ""
            f = MARK_FILL.get(sval[:1])
            if f:
                cell.fill = f
                if len(sval) == 1:
                    cell.font = Font(name="微软雅黑", size=11, bold=True,
                                     color={"●": "2E7D32", "◐": "9C6500", "○": "A6A6A6"}[sval])
                else:
                    cell.font = Font(name="微软雅黑", size=8,
                                     color={"●": "2E7D32", "◐": "9C6500", "○": "A6A6A6"}[sval[:1]])
        ws.row_dimensions[r].height = 30

    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    ws.freeze_panes = freeze
    ws.auto_filter.ref = f"A3:{get_column_letter(len(headers))}{3 + len(rows)}"

    # 打印/导出设置：横向 + 按宽缩放 + 重复表头
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A3
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.print_title_rows = "3:3"
    ws.page_margins.left = ws.page_margins.right = 0.3
    ws.page_margins.top = ws.page_margins.bottom = 0.4


